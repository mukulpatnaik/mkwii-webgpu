#!/usr/bin/env bash
# Build mkw-web: one executable that serves the private browser build of Mario Kart Wii on
# 127.0.0.1 and offers your disc image (a .wbfs/.iso next to it) to the page. See
# tools/web-server/server.js.
#
#   scripts/build-web-server.sh             # work/dist/mkw-web-<os>-<arch>, for this machine
#   scripts/build-web-server.sh --mac-kit   # work/dist/mkw-web-mac-kit.tar.gz: unpack on the Mac
#                                           # and run ./build.sh there (needs Bun on the Mac)
#
# The page files come from BUILD_DIR (default work/Wiicompiled/build-web; build them first with
# scripts/build-private-bundle.sh). The executable and the kit contain translated game code: keep
# them on your own machines, never upload or share them. Your disc image is never put in them.
set -euo pipefail

ROOT="$(cd "$(dirname "$0")/.." && pwd)"
BUILD_DIR="${BUILD_DIR:-$ROOT/work/Wiicompiled/build-web}"
STAGE="$ROOT/work/web-server-build"
DIST="$ROOT/work/dist"
FILES=(WiiCompiled.html WiiCompiled.js WiiCompiled.wasm WiiCompiled.data mkw_disc.wasm mkw_disc_worker.js)

kit=0
case "${1:-}" in
  --mac-kit) kit=1 ;;
  "") ;;
  *) echo "usage: $0 [--mac-kit]" >&2; exit 2 ;;
esac

for f in "${FILES[@]}"; do
  [ -f "$BUILD_DIR/$f" ] || { echo "missing $BUILD_DIR/$f: run scripts/build-private-bundle.sh first" >&2; exit 1; }
done

rm -rf "$STAGE"
mkdir -p "$STAGE/public" "$DIST"
cp "$ROOT/tools/web-server/server.js" "$STAGE/"
{
  echo '// Generated by scripts/build-web-server.sh: the page files embedded in the executable.'
  i=0
  for f in "${FILES[@]}"; do
    cp "$BUILD_DIR/$f" "$STAGE/public/"
    echo "import f$i from './public/$f' with { type: 'file' };"
    i=$((i + 1))
  done
  echo 'export const embeddedFiles = {'
  i=0
  for f in "${FILES[@]}"; do echo "  '$f': f$i,"; i=$((i + 1)); done
  echo '};'
} > "$STAGE/assets.js"

cat > "$STAGE/build.sh" <<'EOF'
#!/bin/sh
# Builds ./mkw-web for this machine from server.js and the page files in public/ (needs Bun:
# https://bun.sh). Then put your disc image (.wbfs or .iso) next to mkw-web and run ./mkw-web.
set -eu
cd "$(dirname "$0")"
command -v bun >/dev/null || { echo "Bun is not installed: see https://bun.sh" >&2; exit 1; }
bun build --compile server.js --outfile "${OUT:-mkw-web}"
echo "Built ${OUT:-mkw-web}. Put your disc image (.wbfs or .iso) next to it and run it."
EOF
chmod +x "$STAGE/build.sh"

if [ "$kit" = 1 ]; then
  tar -czf "$DIST/mkw-web-mac-kit.tar.gz" -C "$STAGE" .
  ls -la "$DIST/mkw-web-mac-kit.tar.gz"
  echo "On the Mac: mkdir mkw-web && tar -xzf mkw-web-mac-kit.tar.gz -C mkw-web && cd mkw-web && ./build.sh"
else
  os="$(uname -s | tr '[:upper:]' '[:lower:]')"; arch="$(uname -m)"
  OUT="$DIST/mkw-web-$os-$arch" "$STAGE/build.sh"
fi
